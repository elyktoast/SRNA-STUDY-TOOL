class EditorialTests(unittest.TestCase):
    def test_rationale_inside_a_result_choice_is_flagged_without_an_intervention_verb(self):
        item={'format':'MC','key':['A'],'options':[
            {'id':'A','text':'Poor, because the stated environment changes the drug fraction'},
            {'id':'B','text':'Favorable result'}, {'id':'C','text':'Unchanged result'}, {'id':'D','text':'Other result'}]}
        self.assertIn('R-6.9',{issue['rule_id'] for issue in check(item)})
        item['options'][0]['text']='Reduced receptor activation'
        self.assertNotIn('R-6.9',{issue['rule_id'] for issue in check(item)})

    def test_short_multiword_drug_name_is_not_a_length_cue_when_visibly_shorter(self):
        item={"format":"MC","key":["C"],"options":[{"id":"A","text":"Desflurane"},
              {"id":"B","text":"Succinylcholine"},{"id":"C","text":"Nitrous oxide"},
              {"id":"D","text":"Isoflurane"}]}
        self.assertNotIn("R-6.8",{i["rule_id"] for i in check(item)})

    def test_actually_longer_short_key_still_flags(self):
        item={"format":"MC","key":["A"],"options":[{"id":"A","text":"Substantially longer explanation"},
              {"id":"B","text":"Small option"},{"id":"C","text":"Other choice"}]}
        self.assertIn("R-6.8",{i["rule_id"] for i in check(item)})

    def test_length(self):
        item = {"format": "MC", "key": ["A"], "stem": "Question?",
                "options": [{"id": k, "text": t} for k,t in zip("ABCD",
                ["A substantially longer explanation than others", "Other", "Third", "Fourth"])]}
        self.assertIn("R-6.8", {e["rule_id"] for e in check(item)})
    def test_verbatim_overlap(self):
        item = {"format": "MC", "key": ["A"],
                "stem": "One two three four five six seven eight nine?",
                "options": [{"id": k, "text": t} for k,t in zip("ABCD", ["Alpha", "Beta", "Gamma", "Delta"])]}
        self.assertIn("R-2.8", {e["rule_id"] for e in check(item,
                      ["one two three four five six seven eight nine ten"])})
    def test_overlap_diagnostic_locates_stem_words_without_echoing_source(self):
        source='one two three four five six seven eight'
        item={'format':'MC','key':['A'],'stem':'Prefix: ONE, two three four five six seven eight?',
              'options':[{'id':'A','text':'Different result'}]}
        issue=next(i for i in check(item,[source]) if i['rule_id']=='R-2.8')
        self.assertEqual((issue['field'],issue['word_start'],issue['word_count']),('stem',1,8))
        self.assertNotIn(source,str(issue))

    def test_overlap_diagnostic_locates_option_without_scanning_cited_quotations(self):
        source='one two three four five six seven eight'
        item={'format':'MC','key':['A'],'stem':'Which response?',
              'options':[{'id':'A','text':'Different response'}, {'id':'B','text':source}]}
        issue=next(i for i in check(item,[source]) if i['rule_id']=='R-2.8')
        self.assertEqual((issue['field'],issue['word_start']),('options.1.text',0))
        item['options'][1]['text']='Another result';item['evidence']=[{'excerpt':source}]
        self.assertNotIn('R-2.8',{i['rule_id'] for i in check(item,[source])})

    def test_no_overlap(self):
        item = {"format": "MC", "key": ["A"], "stem": "Which value?",
                "options": [{"id": k, "text": t} for k,t in zip("ABCD", ["One", "Two", "Three", "Four"])]}
        self.assertEqual(check(item), [])

if __name__ == "__main__":
    unittest.main()


class CaseBoundaryTests(unittest.TestCase):
    def test_rewritten_condition_over_limit_is_diagnosed_without_echoing_text(self):
        from item_board_quality_v2 import canonical_counterfactual, verify_counterfactual, counterfactual_parts
        condition = ('A ring-shaped force transducer is fitted over the thumb, the remaining fingers are immobilized, '
                     'and stimulation of the ulnar nerve is used to record the contraction force generated by the adductor pollicis.')
        self.assertEqual(len(condition), 206)
        alternate = 'An accelerometer records thumb acceleration.'
        q = {'format':'MC','options':[], 'stem':condition+' Which modality is described?',
             'concept_card':{'counterfactual':f'If "{condition}" is replaced by "{alternate}", the best response changes to option(s) B.'}}
        self.assertIsNone(canonical_counterfactual(q['concept_card']['counterfactual']))
        issue = next(i for i in check(q) if i['rule_id']=='R-5.3')
        self.assertEqual((issue['edit_field'],issue['character_count']),('from_text',206))
        self.assertNotIn(condition,str(issue))
        proof = verify_counterfactual(q,counterfactual_parts(q['concept_card']['counterfactual']),
                                      lambda _:self.fail('Invalid edit must not call blind reviewer'))
        self.assertEqual(proof['status'],'flag')
        self.assertEqual(proof['issues'],[issue])

    def test_shortened_condition_still_requires_independent_clinical_verdict(self):
        from item_board_quality_v2 import canonical_counterfactual, verify_counterfactual
        condition = 'The monitor records thumb contraction force.'
        alternate = 'The monitor records thumb acceleration.'
        q = {'item_id':'q','format':'MC','options':[{'id':'A','text':'Force'},{'id':'B','text':'Acceleration'}],
             'key':['A'],'stem':condition+' Which modality is described?',
             'concept_card':{'counterfactual':f'If "{condition}" is replaced by "{alternate}", the best response changes to option(s) B.'}}
        self.assertNotIn('R-5.3',{i['rule_id'] for i in check(q)})
        for answer, status in [('A','flag'),('B','pass')]:
            seen=[]
            def blind(payload):
                seen.append(payload)
                return {'item_id':'q','key':[answer]}
            proof=verify_counterfactual(q,canonical_counterfactual(q['concept_card']['counterfactual']),blind)
            self.assertEqual(proof['status'],status)
            self.assertEqual(len(seen),1)
            self.assertNotIn('key',seen[0])
            self.assertIn(alternate,seen[0]['stem'])

    def test_stale_literal_edit_after_paraphrase_is_held(self):
        q={'format':'MC','options':[],'stem':'The monitor records force. Which modality?',
           'concept_card':{'counterfactual':'If "The monitor senses force." is replaced by "It records acceleration.", the best response changes to option(s) B.'}}
        self.assertIn('R-5.3',{i['rule_id'] for i in check(q)})

    def test_incomplete_case_cannot_run_into_standalone_question(self):
        condition = "The problem is traced to a leak downstream from"
        def item_with_case(condition):
            return {"format": "MC", "options": [], "stem": condition + " Which device detects it?",
                    "concept_card": {"counterfactual":
                        f'If "{condition}" is replaced by "The supply pressure falls.", '
                        'the best response changes to option(s) B.'}}

        item = item_with_case(condition)
        self.assertIn("R-4.2", [issue["rule_id"] for issue in check(item)])
        item = item_with_case("The low-pressure circuit leaks.")
        self.assertNotIn("R-4.2", [issue["rule_id"] for issue in check(item)])
