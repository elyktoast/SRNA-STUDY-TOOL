import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = name => fs.readFileSync(new URL('../equipment/assets/'+name, import.meta.url), 'utf8');
const context = { module: { exports: {} } };
vm.runInNewContext(read('acronym-clarity.js'), context);
const {clarify,expansions} = context.module.exports;
assert.equal(clarify('Check BP, OR, PEEP, PIP and Pplat.'), 'Check BP, OR, PEEP, PIP and Pplat.');
assert.equal(clarify('Assess the DISS and PISS connection.'), 'Assess the diameter index safety system (DISS) and pin index safety system (PISS) connection.');
assert.equal(clarify('DISS inspection prevents DISS mismatch.'), 'diameter index safety system (DISS) inspection prevents DISS mismatch.');
assert.equal(clarify('diameter index safety system (DISS)'), 'diameter index safety system (DISS)');
assert.equal(clarify('DISS-like fitting').startsWith('diameter index safety system (DISS)-like'), true);
assert.equal(clarify('The patient has AGS.'), 'The patient has alpha-gal syndrome (AGS).');
assert.equal(clarify(null), null);
assert.equal(clarify('PEEP PIP Pplat BP OR MAC FGF FRC ETT TIVA TOF PONV'), 'PEEP PIP Pplat BP OR MAC FGF FRC ETT TIVA TOF PONV');
assert.equal(clarify('Vt and MV', {topic:'Respiratory monitoring'}), 'Vt and MV');
assert.equal(clarify('TV and VE', {topic:'Respiratory monitoring'}), 'Vt and MV');
assert.equal(clarify('tidal volume and minute ventilation', {topic:'Respiratory monitoring'}), 'Vt and MV');
assert.equal(clarify('tidal volume (Vt) and minute ventilation (MV)', {topic:'Respiratory monitoring'}), 'tidal volume (Vt) and minute ventilation (MV)');
assert.equal(clarify('Pmean and Raw and Ti and Te'), 'mean airway pressure (Pmean) and airway resistance (Raw) and inspiratory time (Ti) and expiratory time (Te)');
assert.equal(clarify('Mean airway pressure and airway resistance'), 'Mean airway pressure (Pmean) and airway resistance (Raw)');
assert.equal(clarify('PISS', {topic:'Regional and neuraxial anesthesia'}), 'PISS');
assert.equal(clarify('TAP and TAP', {topic:'Regional and neuraxial anesthesia'}), 'transversus abdominis plane (TAP) and transversus abdominis plane (TAP)');
assert.equal(clarify('transversus abdominis plane (TAP)', {topic:'Regional anesthesia'}), 'transversus abdominis plane (TAP)');
assert.ok(Object.isFrozen(expansions));
const loader=read('studio-loader.js');
assert.ok(loader.includes("runtime.loadScript('acronym-clarity.js')"));
assert.ok(loader.indexOf("runtime.loadScript('acronym-clarity.js')")<loader.indexOf("runtime.loadScript('studio-runtime.js')"));
const runtime=read('studio-runtime.js');
assert.ok(runtime.includes("MBUAcronymClarity?.clarify(q.stem,{topic:q.topic})"));
assert.ok(runtime.includes("MBUAcronymClarity?.clarify(q.exp,{topic:q.topic})"));
assert.ok(runtime.includes("MBUAcronymClarity?.clarify(o,{topic:q.topic})"));
console.log('Study Studio acronym clarity tests passed');
